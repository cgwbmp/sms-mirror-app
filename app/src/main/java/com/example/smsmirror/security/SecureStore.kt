package com.example.smsmirror.security

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Stores the SMTP app-password encrypted under a key that lives in the Android
 * Keystore — hardware-backed where the device offers it. The key material never
 * leaves the Keystore; only the ciphertext is written to preferences, so pulling the
 * prefs file off the device yields nothing usable.
 *
 * Direct Keystore rather than Jetpack Security: `EncryptedSharedPreferences` is
 * deprecated, and this needs one secret, not a whole store.
 */
class SecureStore(context: Context) {

    private val prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)

    var smtpPassword: String?
        get() = prefs.getString(KEY_PASSWORD, null)?.let(::decrypt)
        set(value) {
            val editor = prefs.edit()
            if (value.isNullOrEmpty()) {
                editor.remove(KEY_PASSWORD)
            } else {
                editor.putString(KEY_PASSWORD, encrypt(value))
            }
            editor.apply()
        }

    val hasPassword: Boolean get() = prefs.contains(KEY_PASSWORD)

    fun clear() {
        prefs.edit().remove(KEY_PASSWORD).apply()
    }

    // --- crypto ------------------------------------------------------------------

    private fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey())
        val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        // IV is generated by the cipher and prefixed; it is not secret.
        val packed = cipher.iv + ciphertext
        return Base64.encodeToString(packed, Base64.NO_WRAP)
    }

    private fun decrypt(stored: String): String? = try {
        val packed = Base64.decode(stored, Base64.NO_WRAP)
        val iv = packed.copyOfRange(0, GCM_IV_BYTES)
        val ciphertext = packed.copyOfRange(GCM_IV_BYTES, packed.size)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey(), GCMParameterSpec(GCM_TAG_BITS, iv))
        String(cipher.doFinal(ciphertext), Charsets.UTF_8)
    } catch (e: Exception) {
        // Key invalidated (e.g. device restored from backup, lock screen removed) —
        // the secret is unrecoverable, so drop it and let the user re-enter it.
        clear()
        null
    }

    private fun secretKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                // No setUserAuthenticationRequired: the worker must be able to send
                // while the screen is locked.
                .build()
        )
        return generator.generateKey()
    }

    private companion object {
        const val PREFS = "sms_mirror_secrets"
        const val KEY_PASSWORD = "smtp_password"
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "sms_mirror_smtp_key"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val GCM_IV_BYTES = 12
        const val GCM_TAG_BITS = 128
    }
}
